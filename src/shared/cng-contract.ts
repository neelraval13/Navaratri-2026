/**
 * THE CNG WIRE CONTRACT, shared by the browser and the server.
 *
 * Framework-free and dependency-free, like the attendee, prize and dandiya
 * contracts: the screen that renders a member and the endpoint that projects
 * one must agree about every field, or a module quietly starts showing
 * something the privacy boundary does not allow it to show.
 *
 * A CNG MEMBER IS A VOLUNTEER, IDENTIFIED BY NAME — not a registered
 * attendee, and not a badge number. Phase CNG1 modelled them as badges and
 * that was wrong: volunteers do not wear the numbered attendee badges and
 * most never pass the registration desk, so there is no badge to key them by
 * and no honest way to invent one. Phase CNG1.1 corrected it.
 *
 * STORING THE NAME CENTRALLY IS DELIBERATE, and it is the ONE person field
 * these tables hold. No phone, no age, no gender, no WhatsApp link, no
 * payment — none of those are needed to hand somebody a prize. The Badge
 * Register is NOT read when a member is added: a CNG name is whatever the
 * operator typed, matched against nothing.
 *
 * THE NAME IS NOT UNIQUE and the ID is the identity. Two volunteers may
 * genuinely share a name, and refusing the second would be refusing a real
 * person.
 *
 * REMOVAL IS SOFT, because a CNG award must still be able to name its
 * recipient months later. The ACTIVE roster is what `GET` returns; a removed
 * member keeps their awards in history and can receive no new ones.
 */

/**
 * What `PUT /api/prizes` answers.
 *
 * `already-member` is NOT a refusal: the same id with the same name is the
 * retry of a lost response, which is exactly what a client-generated
 * idempotency key is for. The requested state holds, so the authoritative row
 * comes back and the screen shows the member.
 *
 * A COLLISION IS a refusal — the same id with a DIFFERENT name — and it is
 * `409 cng-id-in-use` rather than an outcome, because nothing the operator
 * asked for happened.
 */
export type CngMembershipOutcome = 'added' | 'already-member'

/**
 * ONE MEMBER THE OPERATOR IS ABOUT TO ADD: its id and its name.
 *
 * The id is generated by the BROWSER, once, when the add is prepared — and
 * kept for as long as that dialog is open. That is what makes `PUT`
 * retryable: an ambiguous failure can be sent again with the same id and
 * reaches the same row instead of creating a second one.
 *
 * It is NOT a caller choosing a database key for its own sake. The server
 * accepts it only as the idempotency key, refuses a second use of it under a
 * different name, and still stamps the time and the adding device itself.
 */
export interface CngMemberDraft {
  cngMemberId: string
  name: string
}

/** Which device added or removed a volunteer. A device, never a person. */
export interface CngActingDevice {
  id: string
  name: string
}

/** One ACTIVE membership. A removed member is not returned in the roster. */
export interface CngMember {
  id: string
  /** As the operator typed it, trimmed. The only person field stored. */
  name: string
  /** ISO 8601 UTC, written by the server. Never accepted from a caller. */
  addedAt: string
  addedBy: CngActingDevice
}

/**
 * One CNG prize, from `cng_prize_awards`.
 *
 * `memberName` is JOINED from `cng_members` rather than copied into the
 * ledger: one copy of a person's name, in one place. It is non-nullable
 * because the member row cannot disappear — removal is soft and the award's
 * foreign key is `ON DELETE restrict`.
 *
 * SEVERAL ROWS MAY SHARE A MEMBER, including rows with the same `prizeName`:
 * repeat prizes are legal for volunteers exactly as they are for attendees.
 */
export interface CngPrizeAward {
  id: string
  cngMemberId: string
  memberName: string
  prizeName: string
  /** ISO 8601 UTC, written by the server. Never accepted from a caller. */
  awardedAt: string
  awardedBy: CngActingDevice
}

/* ------------------------------------------------------- the name policy */

/**
 * The database's own ceiling, and the application's.
 *
 * Long enough for any real name with a title or a double-barrelled surname,
 * short enough that a pasted paragraph is refused rather than stored.
 */
export const CNG_NAME_MAX_LENGTH = 120

export type CngNameResult =
  | { ok: true; value: string }
  | { ok: false; message: string }

/**
 * Validates a CNG member's name, and returns the form that is STORED.
 *
 * Surrounding whitespace is trimmed, because that is a transport artifact —
 * a pasted line, a stray tab — rather than part of somebody's name. Nothing
 * else is repaired: internal spacing, capitalisation and punctuation are
 * stored exactly as typed, because a name is not the application's to
 * correct.
 *
 * A blank or whitespace-only name is REFUSED. It is the one thing that
 * identifies the member, so a row without one would be a volunteer nobody
 * could name.
 *
 * SHARED, so the Add form and the endpoint cannot disagree about what is
 * acceptable — the same arrangement `parsePrizeName` has.
 */
export const parseCngMemberName = (value: unknown): CngNameResult => {
  if (typeof value !== 'string') {
    return { ok: false, message: 'Enter the CNG member’s name.' }
  }

  const trimmed = value.trim()

  if (trimmed === '') {
    return { ok: false, message: 'Enter the CNG member’s name.' }
  }

  if (trimmed.length > CNG_NAME_MAX_LENGTH) {
    return {
      ok: false,
      message: `A CNG member’s name must be ${String(CNG_NAME_MAX_LENGTH)} characters or fewer.`,
    }
  }

  return { ok: true, value: trimmed }
}

/**
 * ONE CANDIDATE NAME PER NON-EMPTY LINE, from pasted text.
 *
 * Splits on every line ending — `\r\n`, `\r` and `\n` — because the text came
 * from somewhere else: a phone, a spreadsheet cell, a message. A list that
 * silently became one entry because the paste used Windows line endings would
 * be a confusing failure.
 *
 * Each line is TRIMMED and a line with nothing left is dropped, so blank
 * lines, trailing newlines and a stray indented line cost nothing.
 *
 * DUPLICATES ARE KEPT. If a name was pasted twice the operator sees it twice,
 * which is the truth about their list; de-duplicating would quietly edit it.
 * Two volunteers may also genuinely share a name, so a repeat is not
 * necessarily a mistake — and the preview shows exactly what will be added.
 *
 * IT RESOLVES NOTHING. Phase CNG1 matched pasted names against the Badge
 * Register; there is no register lookup here, no fuzzy matching, no badge, no
 * age and no gender — a CNG name is simply a name.
 */
export const parsePastedCngNames = (text: string): string[] =>
  text
    .split(/\r\n|\r|\n/)
    .map((line) => line.trim())
    .filter((line) => line !== '')
